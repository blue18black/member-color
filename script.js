function startCarousel(){

    const members =
        groups[selectedGroup];

    carouselIndex = 0;

    updateCarousel();

    clearInterval(carouselTimer);

    carouselTimer = setInterval(()=>{

        carouselIndex++;

        if(
            carouselIndex >=
            members.length
        ){
            carouselIndex = 0;
        }

        updateCarousel();

    },2000);

}
