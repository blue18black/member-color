let selectedGroup;
let questions = [];
let currentIndex = 0;
let score = 0;
let mistakes = [];

function showScreen(id){

    document.querySelectorAll(".screen")
        .forEach(e=>e.classList.add("hidden"));

    document.getElementById(id)
        .classList.remove("hidden");
}

function selectGroup(group){

    selectedGroup = group;

    let count =
        groups[group].length;

    document.getElementById("groupTitle")
    .textContent = groupNames[group];

    document.getElementById("questionCount")
        .textContent =
        `全${count}問`;

    showScreen("startScreen");
    startCarousel();
}

function startQuiz(){
    clearInterval(carouselTimer);
    questions =
        [...groups[selectedGroup]];

    questions.sort(
        ()=>Math.random()-0.5
    );

    currentIndex = 0;
    score = 0;
    mistakes = [];

    canAnswer = true;

    document.getElementById("skipBtn").disabled = false;
    document.getElementById("homeBtn").disabled = false;
    createColorButtons();

    showScreen("quizScreen");

    showQuestion();
}

function createColorButtons(){

    const grid =
        document.getElementById("colorGrid");

    grid.innerHTML = "";

    colors.forEach(color=>{

        const btn =
            document.createElement("button");

        btn.className = "color-btn";

        btn.textContent = color.name;

        btn.style.backgroundColor =
            color.code;

        const darkColors = [
            "パープル",
            "ロイヤルブルー",
            "ブルー",
            "ミディアムブルー",
            "ピュアレッド",
            "ホットピンク",
            "ライトレッド",
            "レッド",
            "イタリアンレッド",
            "オレンジ",
            "ラベンダー",
            "エメラルドグリーン",
            "グリーン",
            "ブライトグリーン",
            "ミントグリーン",
        ];

        if(darkColors.includes(color.name)){
            btn.style.color = "white";
        }else{
            btn.style.color = "black";
        }

        btn.onclick = () =>
            answer(color.name);

        grid.appendChild(btn);

    });

}

function showQuestion(){

    const q =
        questions[currentIndex];

    document.getElementById("progress")
        .textContent =
        `${currentIndex+1}/${questions.length}`;

    document.getElementById("memberName")
        .textContent =
        q.name;

    document.getElementById("memberImage")
        .src =
        q.image;
}

let canAnswer = true;

function answer(selected){
    if(!canAnswer) return;

    canAnswer = false;

    const q =
        questions[currentIndex];

    const correct =
        q.color;

    if(selected===correct){

        score++;

        showOverlay(
            `⭕ 正解<br>${correct}`,
            true,
            correct
        );

    }else{

        mistakes.push({
            name:q.name,
            answer:selected,
            correct:correct
        });

        showOverlay(
            `❌ 不正解<br>正解：${correct}`,
            false,
            correct
        );
    }

    setTimeout(nextQuestion,1000);
}

function skipQuestion(){
    if(!canAnswer) return;

    canAnswer = false;

    const q = questions[currentIndex];

    if(q.color === "わからない"){

        score++;

        showOverlay(
            "⭕ 正解<br>メンバーカラー未発表",
            true,
            "わからない"
        );

    }else{

        mistakes.push({
            name:q.name,
            answer:"未回答",
            correct:q.color
        });

        showOverlay(
            `正解：${q.color}`,
            false,
            q.color
        );
    }

    setTimeout(nextQuestion,1000);
}

function nextQuestion(){

    document.getElementById("overlay")
    .className = "hidden";

    currentIndex++;

    if(currentIndex>=questions.length){

        showResult();

        return;
    }
    canAnswer = true;
    showQuestion();

    document
        .querySelectorAll(".color-btn")
        .forEach(btn=>{

            btn.disabled = false;

        });

    document
        .getElementById("skipBtn")
        .disabled = false;
    document
        .getElementById("homeBtn")
        .disabled = false;
}

function showOverlay(text,isCorrect,colorName){

    const overlay =
        document.getElementById("overlay");

    overlay.innerHTML = text;

    overlay.className = "";

    overlay.classList.add("show");

    // 最初に背景をリセット
    overlay.style.background = "white";

    const colorData =
        colors.find(
            c => c.name === colorName
        );

    if(isCorrect){

        if(colorName === "わからない"){

            overlay.style.border =
                "6px solid black";

        }else if(colorData){

            overlay.style.border =
                `6px solid ${colorData.code}`;

            // overlay.style.backgroundColor =
            //     colorData.code;
            // overlay.style.opacity = "0.8";

        }else{

            overlay.style.border =
                "6px solid black";
        }

    }else{

        // overlay.style.border =
        //     "6px solid #005eb8";
        overlay.style.border =
                `6px solid ${colorData.code}`;

    }

    document
        .querySelectorAll(".color-btn")
        .forEach(btn=>{

            btn.disabled = true;

        });

    document
        .getElementById("skipBtn")
        .disabled = true;
    document
        .getElementById("homeBtn")
        .disabled = true;
}

function showResult(){

    showScreen("resultScreen");

    document.getElementById("scoreText")
        .innerHTML =
        `
        ${questions.length}問中
        ${score}問正解
        <br>
        正答率
        ${(score/questions.length*100)
        .toFixed(1)}%
        `;

    const area =
        document.getElementById("mistakes");

    area.innerHTML = "";

    mistakes.forEach(m=>{

        area.innerHTML +=
        `
        <p>
        ❌ ${m.name}<br>
        回答:${m.answer}<br>
        正解:${m.correct}
        </p>
        `;
    });
}

function goHome(){

    showScreen("homeScreen");
}

