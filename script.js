function updateCarousel(){

    const img =
        document.getElementById(
            "carouselImage"
        );

    img.style.opacity = 0;

    setTimeout(()=>{

        const members =
            groups[selectedGroup];

        img.src =
            members[carouselIndex].image;

        document
            .getElementById(
                "carouselName"
            )
            .textContent =
            members[carouselIndex].name;

        img.style.opacity = 1;

    },200);
}

